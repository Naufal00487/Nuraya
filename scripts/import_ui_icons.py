#!/usr/bin/env python3
"""Convert the selected Flaticon UIcons font outlines into native Compose vectors.

Original outlines are retained; only font-coordinate Y direction is converted.
Flaticon free-license attribution must remain visible in Sources & attribution.
Requires fontTools to regenerate; there is no icon-font dependency in Android.
"""
from pathlib import Path
import argparse, re, json, hashlib, urllib.request
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen

ROOT = Path(__file__).resolve().parents[1]
VERSION = '3.3.1'
BASE = f'https://cdn.jsdelivr.net/npm/@flaticon/flaticon-uicons@{VERSION}'
MAPPING = {
    'Add':'plus','ArrowBack':'arrow-left','ArrowForward':'arrow-right','AutoStories':'book-open-cover',
    'Bookmark':'bookmark','BookmarkAdded':'bookmark','BookmarkBorder':'bookmark','Bookmarks':'books',
    'ContentCopy':'copy','Notifications':'bell','WifiOff':'wifi-slash','CheckCircle':'check-circle','ChevronRight':'angle-right','Close':'cross','DarkMode':'moon',
    'DeleteOutline':'trash','Download':'download','DownloadDone':'download','EmojiEvents':'trophy',
    'ExpandLess':'angle-up','ExpandMore':'angle-down','Explore':'compass-alt',
    'Favorite':'heart','FavoriteBorder':'heart','GraphicEq':'waveform-path','Headphones':'headphones',
    'Home':'home','Info':'info','KeyboardArrowUp':'angle-up','LightMode':'sun','LocationOn':'marker',
    'MenuBook':'book-quran','Mic':'microphone','MoreVert':'menu-dots-vertical','OpenInNew':'arrow-up-right-from-square',
    'Palette':'palette','Pause':'pause','PauseCircleOutline':'pause-circle','Person':'user',
    'PlayArrow':'play','PlayCircleOutline':'play-circle','PlaylistAdd':'list-music','PlaylistAddCheck':'list-check',
    'RecordVoiceOver':'circle-microphone-lines','Remove':'minus','RepeatOne':'arrows-repeat-1','School':'graduation-cap',
    'Search':'search','SearchOff':'search','Settings':'settings','Share':'share','SkipNext':'step-forward',
    'SkipPrevious':'step-backward','Speed':'tachometer-fast','Stop':'stop','Translate':'language','Tune':'settings-sliders',
    'Verified':'badge-check','Visibility':'eye','VisibilityOff':'eye-crossed','VolumeOff':'volume-slash',
    'VolumeUp':'volume','WbSunny':'sun','WbTwilight':'sunrise',
    'Calendar':'calendar','Clock':'clock','Shield':'shield-check','Globe':'globe',
    'Accessibility':'universal-access','Qibla':'kaaba','Hadith':'book-alt','Quran':'book-quran',
}

def fetch(url, target):
    if not target.exists():
        target.parent.mkdir(parents=True,exist_ok=True)
        with urllib.request.urlopen(url,timeout=30) as response:target.write_bytes(response.read())
    return target.read_bytes()

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--cache',type=Path,default=Path('/tmp/nuraya-uicons'));args=parser.parse_args()
    css=fetch(BASE+'/css/regular/rounded.css',args.cache/'rounded.css').decode()
    font_bytes=fetch(BASE+'/css/uicons-regular-rounded-KDJ23353.woff',args.cache/'rounded.woff')
    license_bytes=fetch(BASE+'/LICENSE',args.cache/'LICENSE')
    codes={name:int(code,16) for name,code in re.findall(r'\.fi-rr-([a-z0-9-]+):before\{content:"\\([0-9a-f]+)"\}',css)}
    missing=set(MAPPING.values())-codes.keys()
    if missing:raise SystemExit('Unavailable icon names: '+str(sorted(missing)))
    font=TTFont(args.cache/'rounded.woff');glyphs=font.getGlyphSet();cmap=font.getBestCmap();upm=font['head'].unitsPerEm
    generated=['// Generated by scripts/import_ui_icons.py. Icons by Flaticon: https://www.flaticon.com/uicons',
        '// Flaticon free license; see docs/licenses/FLATICON.txt. Outlines are not AI generated.',
        'package com.nuraya.app.ui.icons','',
        'import androidx.compose.ui.graphics.Color','import androidx.compose.ui.graphics.SolidColor',
        'import androidx.compose.ui.graphics.vector.ImageVector','import androidx.compose.ui.graphics.vector.PathParser',
        'import androidx.compose.ui.unit.dp','',
        'object AppIcons {','    object Outlined {']
    icons=[]
    for key,name in MAPPING.items():
        glyph=cmap[codes[name]];pen=SVGPathPen(glyphs)
        glyphs[glyph].draw(TransformPen(pen,(1,0,0,-1,0,font['hhea'].ascent)))
        path=pen.getCommands()
        width=font['hmtx'][glyph][0];height=font['hhea'].ascent-font['hhea'].descent
        generated.append(f'        val {key}: ImageVector by lazy {{ vector("{name}", {width}f, {height}f, {json.dumps(path)}) }}')
        icons.append({'property':key,'icon':name,'codepoint':hex(codes[name]),'outlineSha256':hashlib.sha256(path.encode()).hexdigest()})
    generated += ['    }','    val Filled get() = Outlined','    object AutoMirrored {',
        '        val Outlined get() = AppIcons.Outlined','        val Filled get() = AppIcons.Outlined','    }',
        '    private fun vector(name: String, width: Float, height: Float, path: String) =',
        '        ImageVector.Builder(name = "Flaticon.$name", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = width, viewportHeight = height)',
        '            .addPath(pathData = PathParser().parsePathString(path).toNodes(), fill = SolidColor(Color.Black)).build()', '}', '']
    target=ROOT/'app/src/main/java/com/nuraya/app/ui/icons/AppIcons.kt';target.parent.mkdir(exist_ok=True);target.write_text('\n'.join(generated))
    licenses=ROOT/'docs/licenses';licenses.mkdir(exist_ok=True);(licenses/'FLATICON.txt').write_bytes(license_bytes)
    metadata={'provider':'Flaticon UIcons','version':VERSION,'website':'https://www.flaticon.com/uicons','requestedCategory':'https://www.flaticon.com/free-icons/ui',
        'fontSource':BASE+'/css/uicons-regular-rounded-KDJ23353.woff','fontSha256':hashlib.sha256(font_bytes).hexdigest(),
        'license':'Flaticon free license with attribution','icons':icons}
    (ROOT/'docs/sources/flaticon-icons.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print('Generated',len(icons),'native vector properties from Flaticon outlines.')

if __name__=='__main__':main()
